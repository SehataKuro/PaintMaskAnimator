def paint(c):
    c.ensure_editable_key()
    c.push_layer_undo()
    c.active_layer.image.setPixelColor(5, 5, QColor("magenta"))
    c.cellChanged.emit(c.current_frame, c.active_layer_index)


def payload(path):
    with ZipFile(path) as archive:
        meta = json.loads(archive.read("project.json"))
        return {"metadata": meta,
                "pngs": {name: pixels(QImage.fromData(archive.read(name)))
                         for name in sorted(archive.namelist()) if name.endswith(".png")}}


@pytest.mark.parametrize("kind", ["short-key", "short-blank", "ragged-pending", "negative", "zero",
                                   "retained", "unnumbered"])
def test_raw_visibility(window, kind):
    if kind in ("negative", "zero"):
        frames = [Frame([slot(1, "red", has_content=True, is_blank_key=True,
                              exposure=-5 if kind == "negative" else 0)]), Frame([slot()])]
    elif kind == "ragged-pending":
        frames = [Frame([slot(7, "red", has_content=True, exposure=4),
                         slot(8, "blue", has_content=True, exposure=3)]),
                  Frame([slot(99, "green", has_content=True, sequence_only=True)]),
                  Frame([]), Frame([slot()]), Frame([])]
    elif kind == "unnumbered":
        frames = [Frame([slot(None, "red", has_content=True, exposure=2)]), Frame([slot()])]
    elif kind == "retained":
        frames = [Frame([slot(1, "red", has_content=True)]),
                  Frame([slot(1, "green", is_blank_key=True)]), Frame([slot(1, "blue")])]
    else:
        blank = kind == "short-blank"
        frames = [Frame([slot(1, "red", has_content=True, exposure=20)]),
                  Frame([slot(2, "green", has_content=not blank, is_blank_key=blank, exposure=2)]),
                  Frame([]), Frame([]), Frame([slot()])]
    # Raw sheet and image resolution are distinct observations; no old oracle at runtime.
    from paintmaskanimator.timeline_resolution import resolve_exposures
    expanded = expand_legacy(snapshot_frames(frames))
    def dense_frames(references, source_keys):
        return [Frame([Layer("A", frames[source_keys[i][li]].layers[li].image
                                   if source_keys[i][li] >= 0 else image(),
                            has_content=ref.kind == "CELL", is_blank_key=ref.kind == "BLANK",
                            sequence_number=ref.number,
                            blank_start=expanded.positions[i][li].blank_start)
                       for li, ref in enumerate(row)]) for i, row in enumerate(references)]
    visible = dense_frames(expanded.sheet, expanded.sheet_keys)
    images = dense_frames(expanded.resolved, expanded.resolve_keys)
    keys = resolve_exposures(images).tolist()
    resolved = [[pixels(images[key].layers[li].image) if key >= 0 else None
                 for li, key in enumerate(keys_at)] for keys_at in keys]
    golden(f"raw/{kind}", {"numbers": numbers(visible), "resolved": resolved})


