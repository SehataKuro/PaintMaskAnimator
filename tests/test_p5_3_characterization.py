def pixels(img):
    if img is None:
        return None
    rgba = img.convertToFormat(QImage.Format.Format_RGBA8888)
    data = bytes(rgba.constBits())
    return {"size": [rgba.width(), rgba.height()],
            "rgba_runs": [[value.hex(), sum(1 for _ in run)] for value, run in
                          groupby(data[i:i + 4] for i in range(0, len(data), 4))]}


def numbers(frames):
    return [[("BLANK" if e.is_blank else "EMPTY" if e.is_empty else
              f"CELL:{e.number}" if isinstance(e.number, int) else "UNNUMBERED")
             for e in row] for row in sheet_from_frames(frames)]


def history(stack):
    return [[type(e).__name__, history_label_for(e)] for e in stack]


def brief(c):
    return {"numbers": numbers(c.frames), "cursor": [c.current_frame, c.active_layer_index],
            "undo": history(c.undo_stack), "redo": history(c.redo_stack)}


def observe(c):
    result = brief(c)
    result["mode"] = c.timeline_mode
    result["render"] = [pixels(c.composite(i, white=False)) for i in range(len(c.frames))]
    result["spans"] = [[(list(block) if (block := c.timeline_block_at(i, li)) is not None else None) for li in range(len(c.layers))]
                       for i in range(len(c.frames))]
    result["tween"] = [[{"spec": e.tween, "member": e.tween_member} for e in row]
                       for row in sheet_from_frames(c.frames)]
    result["tracks"] = [{
        "bank": {str(n): {"image": pixels(cell.image), "initial": pixels(cell.initial_image),
                          "name": cell.cell_name} for n, cell in sorted(t.cells.items())},
        "hints": {str(n): asdict(h) for n, h in sorted(t.legacy_archive_hints.items())},
        "unplaced": sorted(c._document.unplaced_numbers(t)),
        "pending": [[e.column, e.slot.sequence_number] for e in c._document.pending_entries(t)],
    } for t in c._document.tracks]
    return result


class Recorder:
    def __init__(self, c):
        self.c, self.events, self.states = c, [], []
        for name in ("cellChanged", "changed", "selectionChanged", "selectionCleared", "colorUsed"):
            getattr(c, name).connect(lambda *args, name=name: self.signal(name, args))

    def signal(self, name, args):
        self.events.append({"signal": name,
                            "args": [list(a.getRgb()) if isinstance(a, QColor) else a for a in args],
                            "state": brief(self.c)})

    def take(self, phase):
        self.states.append({"phase": phase, "state": observe(self.c), "events": self.events[:]})
        self.events.clear()

    def roundtrip(self):
        self.take("after")
        self.c.undo()
        self.take("undo")
        self.c.redo()
        self.take("redo")


