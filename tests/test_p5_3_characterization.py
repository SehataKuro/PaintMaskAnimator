@pytest.mark.parametrize("column,label", INSERTS, ids=[label for _, label in INSERTS])
def test_insert_paint_save_open(window, tmp_path, monkeypatch, column, label):
    c = sheet(window, other_tail=True)
    r = Recorder(c)
    r.take("before")
    assert window.timeline_ops.insert_frame_at(row(c), column)
    r.take("insert")
    c.undo()
    r.take("insert-undo")
    c.redo()
    r.take("insert-redo")
    c.current_frame = min(column, len(c.frames) - 1)
    paint(c)
    r.roundtrip()
    saved = {}
    for mode in ("normal", "sync", "background"):
        path = tmp_path / f"{mode}.pman"
        monkeypatch.setattr(window.autosave, "path", lambda path=path: path)
        try:
            if mode == "normal":
                assert window.project.write(path)
            elif mode == "sync":
                window.autosave.save()
            else:
                window.autosave.request_save()
                window.autosave._pending.result(timeout=10)
            saved[mode] = payload(path)
        finally:
            if mode != "normal":
                window.autosave.clear()
    r.take("saved")
    assert window.project.open(tmp_path / "normal.pman")
    r.take("open")
    golden(f"insert/{label}", {"states": r.states, "saved": saved})


